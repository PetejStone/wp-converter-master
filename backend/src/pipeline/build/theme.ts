export const THEME_SLUG = "scorpion-converted";

export interface PerPageAssets {
  // Page slug (path-derived, e.g. "home", "about-us",
  // "residential-plumbing-services-drain-lines-clogged-drains") → ordered
  // list of CSS / JS filenames the page should load. Filenames resolve to
  // files in theme/css/ and theme/js/ respectively, plus the per-page
  // inline CSS filename (also written to theme/css/).
  cssFilenamesByPageSlug: Map<string, string[]>;
  jsFilenamesByPageSlug: Map<string, string[]>;
}

export interface ThemeInputs {
  siteTitle: string;
  // Every CSS / JS filename present in theme/css/ and theme/js/. Each
  // becomes a wp_register_style/script call so the per-page enqueue can
  // reference it by handle.
  cssFilenames: string[];
  jsFilenames: string[];
  perPage: PerPageAssets;
  // Page slug used for `post_type=post` views via single.php. Picked
  // from the dominant Scorpion-template exemplar page among blog posts.
  // null when the site has no blog posts (post enqueue branch becomes a
  // no-op).
  postPageSlug: string | null;
  // Purpose-built admin metabox for each Scorpion-system CPT. Each spec
  // generates a labeled-input metabox registered against that CPT's
  // post type (see cpt-metabox.ts / cpts/<system>.ts). Empty array
  // means no system CPTs were emitted.
  cptMetaboxes: CptMetaboxSpec[];
  // CF7 mail-sent redirect targets, built from the ingest page list.
  // Drives the wp_footer JS handler that navigates form submitters to
  // either the host page's own thank-you child or a site-wide fallback
  // (typically /contact-us/thank-you/). Empty map + null fallback skips
  // emitting the handler entirely.
  thankYouRedirects: ThankYouRedirects;
}

// Apache rewrite snippet that ships alongside the export. The theme's
// `init`-hook intercept for `/common/usc/p/<name>.{js,css,html}` only
// works on hosts that route static-file-shaped requests through PHP.
// Edge-cached hosts (GoDaddy Managed WordPress is the known case) 404
// these requests at the gateway before WP boots. Merging this snippet
// into the WP root .htaccess rewrites the request to the theme path
// before the gateway's static-file 404, bypassing the intercept entirely.
export function buildHtaccessAdditions(): string {
  return `# Scorpion CMS → WordPress conversion — .htaccess additions
#
# Paste the directives below into your WordPress root .htaccess,
# ABOVE the "# BEGIN WordPress" marker.
#
# 1. The <IfModule mod_rewrite.c> block rewrites Scorpion's runtime
#    /common/usc/p/<name>.{js,css,html} requests to the converted theme
#    so they resolve on hosts that 404 unknown static paths at the edge
#    before the request reaches PHP (e.g. GoDaddy Managed WordPress).
#    Safe to skip on hosts where /common/usc/p/<name>.js already returns
#    200 — the theme's functions.php intercept handles those automatically.
#
# 2. ErrorDocument 500 points Apache's 500-handler at the converted
#    theme's 500.php. theme/404.php is picked up by WordPress's own
#    template hierarchy and does not need an Apache directive.

<IfModule mod_rewrite.c>
RewriteEngine On
RewriteRule ^common/usc/p/(.+\\.(?:js|css|html))$ /wp-content/themes/${THEME_SLUG}/js/$1 [L]
</IfModule>

ErrorDocument 500 /wp-content/themes/${THEME_SLUG}/500.php
`;
}

